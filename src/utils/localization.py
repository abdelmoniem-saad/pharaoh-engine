def set_language(lang: str) -> None:
    """Set the active language."""
    global _current_language
    if lang in _strings:
        _current_language = lang


def get_language() -> str:
    """Get the current language code."""
    return _current_language


def t(key: str) -> str:
    """Translate a key to the current language. Falls back to English."""
    lang_table = _strings.get(_current_language, _strings["en"])
    return lang_table.get(key, _strings["en"].get(key, f"[{key}]"))


def t_format(key: str, **kwargs) -> str:
    """Translate a key and format with keyword arguments."""
    template = t(key)
    try:
        return template.format(**kwargs)
    except (KeyError, IndexError):
        return template


def display_name(entity, lang: str | None = None) -> str:
    """
    Get the display name for a club or player based on current language.

    Args:
        entity: A Club or Player model (must have `name` and optionally `name_ar`).
        lang: Override language; defaults to current language.
    """
    use_lang = lang or _current_language
    if use_lang == "ar":
        ar_name = getattr(entity, "name_ar", "")
        if ar_name:
            return ar_name
    return entity.name


def is_rtl() -> bool:
    """Check if the current language is right-to-left."""
    return _current_language == "ar"
